"""Write tiny fake Bio-Rad Image Lab .scn files for tests.

A real .scn is a MIME container (the same packaging format as email):

    top-level header            multipart/mixed
    ├── ItemHeaderTag           XML: file info
    ├── ScanImageTag0           multipart/mixed (nested)
    │   ├── ImageData           raw uint16 little-endian pixels
    │   └── ImageHeader         XML: width, height, mm size, scan attributes
    └── ItemLaneAndBandDataTag  XML: Image Lab's own lane/band analysis

This factory reproduces that structure with a tiny image, so tests know
exactly which pixels and metadata the loader should return.
"""

from pathlib import Path

import numpy as np

CRLF = b"\r\n"


def _part(content_type: str, description: str, body: bytes) -> bytes:
    header = (
        f"Content-Type: {content_type}\r\n"
        f"Content-Length: {len(body)}\r\n"
        f"Content-Description: {description}\r\n"
        "X-EntityRank: middle\r\n"
    ).encode()
    return header + CRLF + body + CRLF


def image_header_xml(width, height, application="Coomassie Blue",
                     size_mm=(106.076, 87.9836), zero_is="white") -> bytes:
    return (
        "<!DOCTYPE XML>\n<root>\n"
        f' <size_pix width="{width}" height="{height}"/>\n'
        f' <size_mm width="{size_mm[0]}" height="{size_mm[1]}" known="true"/>\n'
        ' <scanner data_ceiling="65535" max_value="65535"/>\n'
        f' <image zero_is="{zero_is}"/>\n'
        " <scan_attributes>\n"
        '  <imager name="Imager" value="ChemiDoc MP" type="0"/>\n'
        '  <exposure_time name="Exposure Time (sec)" value="0.49" type="1"/>\n'
        f'  <application name="Application" value="{application}" type="0"/>\n'
        " </scan_attributes>\n</root>\n"
    ).encode()


def lane_analysis_xml(frame, lanes, standard_kda=(250, 150, 100, 75, 50, 37, 25, 20, 15, 10)) -> bytes:
    """Image Lab's ItemLaneAndBandDataTag.

    frame: (left, top, right, bottom) in pixels
    lanes: list of dicts with keys label, top_anchor, bottom_anchor, width, std, bands
           (anchors = lane centre as fraction of frame width, at top / bottom;
            bands = rel_peak values, fraction of the frame height)
    """
    left, top, right, bottom = frame
    std = "".join(f'<std_value notVisibleInSF="0" label="" value="{v}"/>' for v in standard_kda)
    lane_xml = ""
    for lane in lanes:
        bands = "".join(f'<band rel_peak="{b}" rel_first="{b - 0.01}" rel_last="{b + 0.01}"/>'
                        for b in lane["bands"])
        lane_xml += (
            f"<lane><label>{lane['label']}</label>"
            f"<top_anchor>{lane['top_anchor']}</top_anchor>"
            f"<bottom_anchor>{lane['bottom_anchor']}</bottom_anchor>"
            f"<rel_spline><rel_spline_pt tLine=\"0.5\" tNorm=\"0\"/></rel_spline>"
            f"<lane_width>{lane['width']}</lane_width>"
            f"<std_lane>{'true' if lane['std'] else 'false'}</std_lane>"
            f"<bands>{bands}</bands></lane>"
        )
    return (
        "<!DOCTYPE XML>\n<root><lane_and_band_analysis channel=\"0\"><lane_frame>"
        f'<top_left y="{top}" x="{left}"/><top_right y="{top}" x="{right}"/>'
        f'<bottom_left y="{bottom}" x="{left}"/><bottom_right y="{bottom}" x="{right}"/>'
        f"<standard><name>Bio-Rad Precision Plus</name><std_values>{std}</std_values></standard>"
        f"<lanes>{lane_xml}</lanes>"
        "</lane_frame></lane_and_band_analysis></root>"
    ).encode()


def write_fake_scn(path: Path, pixels: np.ndarray, include_image=True,
                   lane_analysis: bytes | None = None, **header_kwargs) -> Path:
    """Write `pixels` (2D uint16) as a minimal but structurally real .scn file.

    lane_analysis: optional XML from lane_analysis_xml(), stored like Image Lab does.
    """
    height, width = pixels.shape
    outer, inner = "OUTER-BOUNDARY", "INNER-BOUNDARY"

    inner_parts = b""
    if include_image:
        inner_parts += f"--{inner}\r\n".encode() + _part(
            "application/octet-stream", "ImageData", pixels.astype("<u2").tobytes())
    inner_parts += f"--{inner}\r\n".encode() + _part(
        'text/xml; charset="utf8"', "ImageHeader", image_header_xml(width, height, **header_kwargs))
    inner_parts += f"--{inner}--\r\n".encode()

    data = (
        b"MIME-Version: 1.0 (Generated by Image Lab 6.0.1)\r\n"
        + f'Content-Type: multipart/mixed; boundary="{outer}"\r\n'.encode()
        + b"Content-Description: Image Lab Image File\r\n\r\n"
        + f"--{outer}\r\n".encode()
        + _part('text/xml; charset="utf8"', "ItemHeaderTag", b"<root><name>fake</name></root>")
        + f"--{outer}\r\n".encode()
        + f'Content-Type: multipart/mixed; boundary="{inner}"\r\n'.encode()
        + b"Content-Description: ScanImageTag0\r\n\r\n"
        + inner_parts
        + (f"--{outer}\r\n".encode()
           + _part('text/xml; charset="utf8"', "ItemLaneAndBandDataTag", lane_analysis)
           if lane_analysis is not None else b"")
        + f"--{outer}--\r\n".encode()
    )
    path.write_bytes(data)
    return path
